package com.argdigital.aronexa.patient;

import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;
import java.security.GeneralSecurityException;
import java.security.SecureRandom;
import java.time.Clock;
import java.time.LocalDate;
import java.util.Base64;
import java.util.HexFormat;
import java.util.UUID;
import javax.crypto.Mac;
import javax.crypto.spec.SecretKeySpec;

/**
 * P01-T07-C2: pure registration command validation and identifier primitives.
 *
 * No persistence, patient HTTP route, permissions, patient data logging or
 * original-database access is introduced here. This is a reusable core for a
 * separately reviewed atomic PostgreSQL registration transaction.
 */
public final class PatientRegistrationRules {
    private static final String CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";
    private static final int MAX_NAME_LENGTH = 180;
    private static final int MAX_IDEMPOTENCY_LENGTH = 128;
    private PatientRegistrationRules() {}

    public enum BirthDatePrecision { UNKNOWN, EXACT, ESTIMATED }

    /** Deliberately excludes contacts, guardianship and self-service. */
    public record Intake(String displayName, BirthDatePrecision birthDatePrecision,
                         LocalDate dateOfBirth) {}

    public record ValidatedIntake(String displayName, String normalizedMatchName,
                                  BirthDatePrecision birthDatePrecision, LocalDate dateOfBirth) {}

    public static ValidatedIntake validate(Intake intake, Clock clock) {
        if (intake == null || clock == null) throw new IllegalArgumentException("Invalid registration input");
        String name = intake.displayName();
        if (name == null) throw new IllegalArgumentException("Invalid patient name");
        name = name.strip().replaceAll("\\s+", " ");
        if (name.length() < 2 || name.length() > MAX_NAME_LENGTH
                || name.codePoints().noneMatch(Character::isLetter)
                || name.codePoints().anyMatch(c -> Character.isISOControl(c) || c == '<' || c == '>')) {
            throw new IllegalArgumentException("Invalid patient name");
        }
        if (intake.birthDatePrecision() == null) {
            throw new IllegalArgumentException("Birth date precision is required");
        }
        if (intake.birthDatePrecision() == BirthDatePrecision.UNKNOWN && intake.dateOfBirth() != null) {
            throw new IllegalArgumentException("Unknown date cannot have a birth date");
        }
        if (intake.birthDatePrecision() != BirthDatePrecision.UNKNOWN
                && (intake.dateOfBirth() == null || intake.dateOfBirth().isAfter(LocalDate.now(clock)))) {
            throw new IllegalArgumentException("Known birth date must be valid and not in future");
        }
        return new ValidatedIntake(name, name.toLowerCase(java.util.Locale.ROOT),
                intake.birthDatePrecision(), intake.dateOfBirth());
    }

    /** A name/DOB suggestion is never a verified patient identity or authorization. */
    public static boolean requiresManualDuplicateReview(ValidatedIntake candidate,
                                                         ValidatedIntake existing) {
        if (candidate == null || existing == null) throw new IllegalArgumentException("Missing candidate");
        if (!candidate.normalizedMatchName().equals(existing.normalizedMatchName())) return false;
        return candidate.dateOfBirth() == null || existing.dateOfBirth() == null
                || candidate.dateOfBirth().equals(existing.dateOfBirth());
    }

    /** Cryptographically random, not derived from patient information or tenant ID. */
    public static String generateMrn(SecureRandom rng) {
        if (rng == null) throw new IllegalArgumentException("Random source is required");
        StringBuilder value = new StringBuilder("PAT-");
        for (int i = 0; i < 12; i++) value.append(CROCKFORD.charAt(rng.nextInt(CROCKFORD.length())));
        return value.toString();
    }

    /**
     * Privacy-preserving, tenant/actor/branch/operation-bound idempotency digest.
     * Key must be high entropy and securely generated by the caller.
     * The secret must come from a protected runtime secret, not this repository.
     */
    public static String keyDigest(byte[] secret, UUID tenantId, UUID actorMembershipId,
                                   UUID branchId, String operation, String idempotencyKey) {
        if (secret == null || secret.length < 32 || tenantId == null || actorMembershipId == null
                || branchId == null || operation == null || !operation.matches("[A-Z_]{3,40}")
                || idempotencyKey == null || idempotencyKey.length() < 20
                || idempotencyKey.length() > MAX_IDEMPOTENCY_LENGTH
                || !idempotencyKey.matches("[A-Za-z0-9_-]+")) {
            throw new IllegalArgumentException("Invalid idempotency configuration");
        }
        // Length-prefixed fields avoid ambiguous joins of user-controlled strings.
        byte[][] fields = {tenantId.toString().getBytes(StandardCharsets.UTF_8),
                actorMembershipId.toString().getBytes(StandardCharsets.UTF_8),
                branchId.toString().getBytes(StandardCharsets.UTF_8),
                operation.getBytes(StandardCharsets.UTF_8),
                idempotencyKey.getBytes(StandardCharsets.UTF_8)};
        int size = java.util.Arrays.stream(fields).mapToInt(f -> 4 + f.length).sum();
        ByteBuffer canonical = ByteBuffer.allocate(size);
        for (byte[] field : fields) canonical.putInt(field.length).put(field);
        try {
            Mac mac = Mac.getInstance("HmacSHA256");
            mac.init(new SecretKeySpec(secret, "HmacSHA256"));
            return HexFormat.of().formatHex(mac.doFinal(canonical.array()));
        } catch (GeneralSecurityException failure) {
            throw new IllegalStateException("Cryptographic primitive unavailable", failure);
        }
    }

    /**
     * Canonical payload digest is not the same as idempotency-key digest:
     * reusing a key with different intake must be rejected by storage.
     */
    public static String payloadFingerprint(ValidatedIntake intake) {
        if (intake == null) throw new IllegalArgumentException("Missing intake");
        String date = intake.dateOfBirth() == null ? "" : intake.dateOfBirth().toString();
        String canonical = Base64.getUrlEncoder().withoutPadding().encodeToString(
                intake.displayName().getBytes(StandardCharsets.UTF_8)) + ":"
                + intake.birthDatePrecision().name() + ":" + date;
        try {
            return HexFormat.of().formatHex(
                    java.security.MessageDigest.getInstance("SHA-256")
                            .digest(canonical.getBytes(StandardCharsets.UTF_8)));
        } catch (GeneralSecurityException failure) {
            throw new IllegalStateException("Cryptographic primitive unavailable", failure);
        }
    }
}
